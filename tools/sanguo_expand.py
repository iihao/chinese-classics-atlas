def main():
    with open(PATH, encoding="utf-8") as f:
        d = json.load(f)

    have_c = {c["id"] for c in d["characters"]}
    added_c = 0
    for cid, name, alias, faction, role, chapters, summary, detail, history in NEW_CHARACTERS:
        if cid in have_c:
            continue
        d["characters"].append({
            "id": cid, "name": name, "alias": alias, "faction": faction,
            "role": role, "chapters": chapters, "summary": summary,
            "detail": detail, "history": history,
        })
        added_c += 1

    have_ids = {c["id"] for c in d["characters"]}
    seen_rel = {(r["a"], r["b"], r["label"]) for r in d["relations"]}
    added_r = 0
    for a, b, label, group, ch in NEW_RELATIONS:
        for x in (a, b):
            if x not in have_ids:
                sys.exit(f"关系引用了不存在的人物: {x}")
        key = (a, b, label)
        if key in seen_rel or (b, a, label) in seen_rel:
            continue
        d["relations"].append({"a": a, "b": b, "label": label, "group": group, "chapter": ch})
        seen_rel.add(key)
        added_r += 1

    with open(PATH, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print(f"新增人物 {added_c}，新增关系 {added_r}")
    print(f"合计：人物 {len(d['characters'])}，关系 {len(d['relations'])}")


if __name__ == "__main__":
    main()
